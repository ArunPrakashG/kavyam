"""Generate features/modern_ligatures.fea and features/traditional.fea from data/."""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from kavyam_glyphs import ROOT, modern_ligatures, traditional_ligatures  # noqa: E402

AKHAND = {"ക്ഷ", "ജ്ഞ"}
HEADER = "# GENERATED by tools/gen_features.py from data/ - do not edit by hand.\n\n"


def sub_line(lig: dict, target: str) -> str:
    return f"        sub {' '.join(lig['seq'])} by {target};  # {lig['text']}\n"


def modern() -> str:
    ligs = modern_ligatures()
    akhn = [l for l in ligs if l["text"] in AKHAND]
    cjct = [l for l in ligs if l["text"] not in AKHAND]
    out = HEADER
    for tag, group in (("akhn", akhn), ("cjct", cjct)):
        out += f"feature {tag} {{\n    lookup modern_{tag} {{\n"
        out += "".join(sub_line(l, l["name"]) for l in group)
        out += f"    }} modern_{tag};\n}} {tag};\n\n"
    return out


def traditional() -> str:
    modern_names = {l["name"] for l in modern_ligatures()}
    out = HEADER
    out += 'feature ss01 {\n    featureNames {\n        name "Traditional lipi (preview)";\n    };\n'
    out += "    lookup trad_new {\n"
    for l in traditional_ligatures():
        if l["name"] not in modern_names:
            out += sub_line(l, l["name"] + ".trad")
    out += "    } trad_new;\n    lookup trad_alt {\n"
    for l in traditional_ligatures():
        if l["name"] in modern_names:
            out += f"        sub {l['name']} by {l['name']}.trad;  # {l['text']}\n"
    out += "    } trad_alt;\n} ss01;\n"
    return out


def flatten(main: Path) -> str:
    """Inline include() statements so the text works from any UFO location."""
    def inline(m: re.Match) -> str:
        return (main.parent / m.group(1)).read_text(encoding="utf-8")
    return re.sub(r"^include\((.+?)\);.*$", inline, main.read_text(encoding="utf-8"),
                  flags=re.M)


def main() -> None:
    feats = ROOT / "features"
    (feats / "modern_ligatures.fea").write_text(modern(), encoding="utf-8")
    (feats / "traditional.fea").write_text(traditional(), encoding="utf-8")
    flat = flatten(feats / "main.fea")
    ufos = sorted((ROOT / "sources").glob("*.ufo"))
    for ufo in ufos:
        (ufo / "features.fea").write_text(flat, encoding="utf-8")
    print(f"wrote generated .fea files; synced features into {len(ufos)} UFOs")


if __name__ == "__main__":
    main()
